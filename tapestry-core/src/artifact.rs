//! The artefact envelope (directive §19) and content addressing (§32).
//!
//! Artefact identity is stable across transport: the id and digest live in
//! the envelope, never in a transport address.

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use sha2::{Digest as _, Sha256};

use crate::ids::{ArtifactId, SessionId};
use crate::{Result, TapestryError};

/// The kind of an artefact. Determines presentation surface.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum ArtifactKind {
    Image,
    ImageSet,
    Video,
    Audio,
    WebCapture,
    Document,
    ModelPreview,
    Telemetry,
    Composite,
}

/// Pixel dimensions for visual artefacts.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Dimensions {
    pub width: u32,
    pub height: u32,
}

/// Where an artefact came from. Provenance is preserved, never collapsed.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "origin", rename_all = "snake_case", deny_unknown_fields)]
pub enum Provenance {
    /// Generated by an agent/model.
    Generated {
        producer: String,
        model: Option<String>,
    },
    /// Derived from another artefact (e.g. thumbnail, transcode).
    Derived {
        source: ArtifactId,
        operation: String,
    },
    /// Supplied by a human or external process.
    External { producer: String },
}

/// The complete semantic envelope for an artefact.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Artifact {
    pub id: ArtifactId,
    pub session_id: SessionId,
    /// Revision within the session; monotonically increasing.
    pub revision: u32,
    pub kind: ArtifactKind,
    /// IANA media type, verified before presentation (§28 MIME verification).
    pub mime: String,
    /// Storage URI, typically `sha256/<digest>` in a content-addressed cache.
    pub uri: String,
    /// Hex-encoded SHA-256 of the content.
    pub digest: String,
    pub byte_length: u64,
    pub dimensions: Option<Dimensions>,
    /// Duration in milliseconds, for timed media.
    pub duration_ms: Option<u64>,
    pub codec: Option<crate::capability::Codec>,
    pub provenance: Provenance,
    pub created_at: DateTime<Utc>,
    /// Artefacts generated as alternatives share a comparison group so the
    /// gallery can present them as candidates.
    pub comparison_group: Option<String>,
    /// Hints for the presentation layer (e.g. "dark", "favour-fit-height").
    pub inspection_hints: Vec<String>,
}

impl Artifact {
    pub fn builder(session_id: SessionId, kind: ArtifactKind) -> ArtifactBuilder {
        ArtifactBuilder {
            artifact: Artifact {
                id: ArtifactId::generate(),
                session_id,
                revision: 1,
                kind,
                mime: String::new(),
                uri: String::new(),
                digest: String::new(),
                byte_length: 0,
                dimensions: None,
                duration_ms: None,
                codec: None,
                provenance: Provenance::External {
                    producer: "unknown".into(),
                },
                created_at: Utc::now(),
                comparison_group: None,
                inspection_hints: Vec::new(),
            },
        }
    }

    /// Validate structural invariants: digest well-formed, uri consistent
    /// with digest, length sane, mime present.
    pub fn validate(&self) -> Result<()> {
        if self.mime.is_empty() {
            return Err(TapestryError::MissingField("mime"));
        }
        if !is_hex_sha256(&self.digest) {
            return Err(TapestryError::InvalidValue {
                field: "digest",
                reason: "not 64 hex characters".into(),
            });
        }
        if !self.uri.is_empty() && self.uri != content_address(&self.digest) {
            return Err(TapestryError::InvalidValue {
                field: "uri",
                reason: format!(
                    "expected `{}` for this digest",
                    content_address(&self.digest)
                ),
            });
        }
        if self.byte_length == 0 {
            return Err(TapestryError::InvalidValue {
                field: "byte_length",
                reason: "artefact must not be empty".into(),
            });
        }
        Ok(())
    }
}

fn is_hex_sha256(s: &str) -> bool {
    s.len() == 64 && s.bytes().all(|b| b.is_ascii_hexdigit())
}

/// Hex SHA-256 of content bytes.
pub fn content_digest(bytes: &[u8]) -> String {
    hex::encode(Sha256::digest(bytes))
}

/// The content-addressed cache key for a digest (§32): `sha256/<digest>`.
pub fn content_address(digest: &str) -> String {
    format!("sha256/{digest}")
}

/// Builder for [`Artifact`].
#[derive(Debug)]
pub struct ArtifactBuilder {
    artifact: Artifact,
}

impl ArtifactBuilder {
    pub fn mime(mut self, mime: impl Into<String>) -> Self {
        self.artifact.mime = mime.into();
        self
    }

    /// Set content, computing digest, uri and length from the bytes.
    pub fn content(mut self, bytes: &[u8]) -> Self {
        let digest = content_digest(bytes);
        self.artifact.byte_length = bytes.len() as u64;
        self.artifact.digest = digest.clone();
        self.artifact.uri = content_address(&digest);
        self
    }

    pub fn dimensions(mut self, width: u32, height: u32) -> Self {
        self.artifact.dimensions = Some(Dimensions { width, height });
        self
    }

    pub fn duration_ms(mut self, ms: u64) -> Self {
        self.artifact.duration_ms = Some(ms);
        self
    }

    pub fn codec(mut self, codec: crate::capability::Codec) -> Self {
        self.artifact.codec = Some(codec);
        self
    }

    pub fn generated_by(mut self, producer: impl Into<String>, model: Option<String>) -> Self {
        self.artifact.provenance = Provenance::Generated {
            producer: producer.into(),
            model,
        };
        self
    }

    pub fn derived_from(mut self, source: ArtifactId, operation: impl Into<String>) -> Self {
        self.artifact.provenance = Provenance::Derived {
            source,
            operation: operation.into(),
        };
        self
    }

    pub fn comparison_group(mut self, group: impl Into<String>) -> Self {
        self.artifact.comparison_group = Some(group.into());
        self
    }

    pub fn hint(mut self, hint: impl Into<String>) -> Self {
        self.artifact.inspection_hints.push(hint.into());
        self
    }

    pub fn revision(mut self, revision: u32) -> Self {
        self.artifact.revision = revision;
        self
    }

    pub fn build(self) -> Artifact {
        self.artifact
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> Artifact {
        Artifact::builder(SessionId::generate(), ArtifactKind::Image)
            .mime("image/png")
            .content(b"png-bytes")
            .dimensions(1920, 1080)
            .generated_by("playbook", Some("test-model".into()))
            .comparison_group("hero")
            .hint("dark")
            .build()
    }

    #[test]
    fn digest_is_stable_sha256() {
        assert_eq!(
            content_digest(b"png-bytes"),
            hex::encode(Sha256::digest(b"png-bytes"))
        );
    }

    #[test]
    fn builder_sets_content_address() {
        let a = sample();
        assert_eq!(a.uri, content_address(&a.digest));
        assert_eq!(a.byte_length, 9);
        assert!(a.validate().is_ok());
    }

    #[test]
    fn validate_rejects_tampered_uri() {
        let mut a = sample();
        a.uri = "sha256/deadbeef".into();
        assert!(a.validate().is_err());
    }

    #[test]
    fn validate_rejects_bad_digest_and_empty_mime() {
        let mut a = sample();
        a.digest = "zz".into();
        assert!(a.validate().is_err());
        a = sample();
        a.mime = String::new();
        assert!(a.validate().is_err());
    }

    #[test]
    fn serde_roundtrip() {
        let a = sample();
        let back: Artifact = serde_json::from_str(&serde_json::to_string(&a).unwrap()).unwrap();
        assert_eq!(a, back);
    }
}
